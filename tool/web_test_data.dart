// Writes test/web/data.g.dart: the files of test/data that the web tests read, as Dart
// constants, since a test compiled for the browser has no dart:io to read them with.
//
//   dart run tool/web_test_data.dart
//
// test/web_test_data_test.dart fails when the committed file is not what this writes.

import 'dart:convert';
import 'dart:io';

/// The files under test/data that test/web reads.
const webTestDataFiles = [
  'apache/interop.avsc',
  'apache/schema-tests.txt',
  'apache/syncInMeta.avro',
  'apache/weather-deflate.avro',
  'apache/weather-snappy.avro',
  'apache/weather-zstd.avro',
  'apache/weather.avro',
  'apache/weather.json',
  'axt/envelope-canonical.json',
  'axt/memo-canonical.json',
  'axt/memo-file.hex',
  'axt/memo-message.hex',
  'compressions/bomb-bzip2.bin',
  'compressions/bomb-xz-sizes.bin',
  'compressions/bomb-xz-x86.bin',
  'compressions/bomb-xz.bin',
  'compressions/bomb-zstandard.bin',
  'compressions/weather-bzip2.avro',
  'compressions/weather-xz.avro',
  'compressions/weather-zstandard.avro',
];

/// The path of the generated file, from the repository root.
const webTestDataPath = 'test/web/data.g.dart';

/// The generated library for the files of [webTestDataFiles], read from [root].
String webTestData({String root = 'test/data'}) {
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/web_test_data.dart from test/data; do not edit.',
    )
    ..writeln()
    ..writeln(
      '/// The files of test/data the web tests read, base64-encoded by path.',
    )
    ..writeln('const webTestFiles = <String, String>{');
  for (final name in webTestDataFiles) {
    final encoded = base64Encode(File('$root/$name').readAsBytesSync());
    out.writeln("  '$name':");
    for (var i = 0; i < encoded.length; i += 72) {
      final end = i + 72 < encoded.length ? i + 72 : encoded.length;
      out.write("      '${encoded.substring(i, end)}'");
      out.writeln(end == encoded.length ? ',' : '');
    }
  }
  out.writeln('};');
  return out.toString();
}

void main() {
  File(webTestDataPath).writeAsStringSync(webTestData());
}
