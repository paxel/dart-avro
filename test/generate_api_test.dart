// Needs dart:io, or test data read from files: not one of the web tests.
@TestOn('vm')
library;

import 'dart:io';

import 'package:avro/generate.dart';
import 'package:test/test.dart';

/// Inside the package, so that `dart format` follows its language version.
final _dir = Directory('.dart_tool/generate_api_test');

/// The executable of the Dart SDK: under `flutter test`, [Platform.resolvedExecutable] is the
/// Flutter tester.
final _dart =
    Platform.resolvedExecutable.split(Platform.pathSeparator).last ==
        (Platform.isWindows ? 'dart.exe' : 'dart')
    ? Platform.resolvedExecutable
    : 'dart';

const _memo = '''
{"type": "record", "name": "Memo", "namespace": "com.example", "fields": [
  {"name": "text", "type": "string"},
  {"name": "body", "type": ["string", "bytes", "null"]},
  {"name": "mood", "type": {"type": "enum", "name": "Mood", "symbols": ["CALM"]}}
]}''';

const _when = '''
{"type": "record", "name": "axt.DateTime", "fields": [{"name": "at", "type": "long"}]}''';

Matcher _throwsGenerate(Matcher message) => throwsA(
  isA<GenerateException>().having((e) => e.message, 'message', message),
);

void main() {
  test('generates from schema texts without files', () {
    final library = generateDart([const SchemaSource('memo.avsc', _memo)]);
    expect(library.warnings, isEmpty);
    expect(
      library.source,
      allOf(
        startsWith(
          '// Generated by avro:generate. Do not edit.\n//\n// From:\n// - memo.avsc\n',
        ),
        contains("import 'package:avro/avro.dart';"),
        contains('final class Memo {'),
        contains('enum Mood {'),
        contains('sealed class MemoBody {'),
        contains('final class MemoBodyString extends MemoBody {'),
      ),
    );
  });

  test('puts prefixes before the names of a namespace', () {
    final source = generateDart(
      [const SchemaSource('when', _when)],
      prefixes: {'axt': 'Axt'},
    ).source;
    expect(source, contains('final class AxtDateTime {'));
  });

  test(
    'rejects a prefix that is not a namespace and an UpperCamelCase name',
    () {
      for (final prefixes in [
        {'axt': 'axt'},
        {'a..b': 'A'},
        {'': 'A'},
      ]) {
        expect(
          () => generateDart([
            const SchemaSource('memo', _memo),
          ], prefixes: prefixes),
          throwsArgumentError,
          reason: '$prefixes',
        );
      }
    },
  );

  test(
    'warns about a type defined twice with other docs, and an unused prefix',
    () {
      final library = generateDart(
        [
          const SchemaSource('a', _memo),
          SchemaSource(
            'b',
            _memo.replaceFirst('"fields"', '"doc": "Other.", "fields"'),
          ),
        ],
        prefixes: {'unused': 'U'},
      );
      expect(library.warnings, [
        '"com.example.Memo" in b differs from a in its docs or attributes; '
            'the definition in a is used',
        'no record or enum is in the namespace unused of --prefix',
      ]);
      expect(() => library.warnings.add('x'), throwsUnsupportedError);
    },
  );

  test('throws GenerateException, naming the source, for a bad schema', () {
    expect(
      () => generateDart([const SchemaSource('bad', '{"type": "record"}')]),
      _throwsGenerate(startsWith('bad: ')),
    );
    expect(
      () => generateDart([const SchemaSource('not json', '{')]),
      _throwsGenerate(startsWith('not json: ')),
    );
  });

  test('throws GenerateException for clashes', () {
    expect(
      () => generateDart([const SchemaSource('when', _when)]),
      _throwsGenerate(
        allOf(
          startsWith('when: '),
          contains('dart:core'),
          contains('--prefix axt=Axt'),
        ),
      ),
    );
    expect(
      () => generateDart([
        const SchemaSource(
          'x',
          '{"type": "record", "name": "a.X", "fields": []}',
        ),
        const SchemaSource(
          'y',
          '{"type": "record", "name": "b.X", "fields": []}',
        ),
      ]),
      _throwsGenerate(
        startsWith('y: "b.X" and "a.X" (x) both give the Dart name X'),
      ),
    );
    expect(
      () => generateDart([
        const SchemaSource(
          'u',
          '[{"type": "record", "name": "R", "fields": [{"name": "u", "type": ["int", "string"]}]}, '
              '{"type": "record", "name": "RU", "fields": []}]',
        ),
      ]),
      _throwsGenerate(contains('the union in the field "u" of "R" and "RU"')),
    );
  });

  test('the command writes the same source, formatted', () async {
    if (_dir.existsSync()) _dir.deleteSync(recursive: true);
    _dir.createSync(recursive: true);
    final schema = '${_dir.path}/memo.avsc';
    File(schema).writeAsStringSync(_memo);
    final fromCommand = '${_dir.path}/command.g.dart';
    final run = await Process.run(_dart, [
      'run',
      'avro:generate',
      schema,
      '-o',
      fromCommand,
    ]);
    expect(run.exitCode, 0, reason: '${run.stdout}${run.stderr}');
    final fromApi = File('${_dir.path}/api.g.dart')
      ..writeAsStringSync(generateDart([SchemaSource(schema, _memo)]).source);
    final format = await Process.run(_dart, ['format', fromApi.path]);
    expect(format.exitCode, 0, reason: '${format.stdout}${format.stderr}');
    expect(fromApi.readAsStringSync(), File(fromCommand).readAsStringSync());
  }, timeout: const Timeout(Duration(minutes: 2)));
}
